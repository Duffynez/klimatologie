import { readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const downloadManifestPath = path.join(root, "audits", "source-download-manifest.json");
const uploadManifestPath = path.join(root, "audits", "google-drive-upload-manifest.json");
const outputPath = path.join(root, "app", "data", "sourceArchive.ts");

const [downloadManifest, uploadManifest] = await Promise.all([
  readJson(downloadManifestPath),
  readJson(uploadManifestPath),
]);

const downloadsByPath = new Map(
  downloadManifest.records
    .filter((record) => record.status === "downloaded" && record.localPath)
    .map((record) => [record.localPath, record]),
);

const archiveFiles = uploadManifest.matches.map((match) => {
  const download = downloadsByPath.get(match.localPath);
  if (!download) throw new Error(`Drive file has no local source record: ${match.localPath}`);
  if (download.id !== match.sourceId) {
    throw new Error(`Source ID mismatch for ${match.localPath}: ${download.id} !== ${match.sourceId}`);
  }

  return {
    sourceId: match.sourceId,
    driveFileId: match.driveFileId,
    relation: download.downloadRelation === "linked-asset-needs-review"
      ? "related-material"
      : "source-copy",
    mimeType: match.mimeType,
    size: match.size,
  };
});

const duplicateIds = archiveFiles
  .map((file) => file.sourceId)
  .filter((sourceId, index, all) => all.indexOf(sourceId) !== index);
if (duplicateIds.length > 0) {
  throw new Error(`Multiple Drive files mapped to one source: ${[...new Set(duplicateIds)].join(", ")}`);
}

archiveFiles.sort((a, b) => a.sourceId.localeCompare(b.sourceId, "en"));

const generated = `// Generated by scripts/sync-google-drive-archive.mjs. Do not edit by hand.\n` +
  `export type SourceArchiveFile = {\n` +
  `  driveFileId: string;\n` +
  `  relation: "source-copy" | "related-material";\n` +
  `  mimeType: string;\n` +
  `  size: number;\n` +
  `};\n\n` +
  `export const sourceArchiveFiles = ${JSON.stringify(
    Object.fromEntries(archiveFiles.map(({ sourceId, ...file }) => [sourceId, file])),
    null,
    2,
  )} as const satisfies Record<string, SourceArchiveFile>;\n`;

await writeFile(outputPath, generated, "utf8");
console.log(`Wrote ${archiveFiles.length} Drive mappings to ${path.relative(root, outputPath)}`);

async function readJson(filePath) {
  return JSON.parse(await readFile(filePath, "utf8"));
}
